public class Day021 {
    public static void main(String[] args) {

        String teksInt = "200";
        String teksByte = "100";

        int angkaInt = Integer.parseInt(teksInt);
        byte angkaByte = Byte.parseByte(teksByte);

        System.out.println("Hasil int: " + angkaInt);
        System.out.println("Hasil byte: " + angkaByte);
    }
}
