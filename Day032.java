package pkg100dayscoding;

public class Day032 {

    public static void main(String[] args) {

        int a = 10;
        int b = 5;

        System.out.println("Hasil AND : " + (a > 5 && b < 10));
        System.out.println("Hasil OR : " + (a > 15 || b < 10));
        System.out.println("Hasil NOT : " + !(a == b));
    }
}
