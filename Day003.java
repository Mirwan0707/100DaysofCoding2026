
package day003;


public class Day003 {

  
    public static void main(String[] args) {
         // \n = pindah baris
        System.out.println("Nama: Mirwan\nNIM: 123456");

        // \t = membuat jarak / tab
        System.out.println("Nama\t: Mirwan");
        System.out.println("NIM\t: 123456");

        // \" = menampilkan tanda petik dua
        System.out.println("Dia berkata: \"Halo\"");

        // \' = menampilkan tanda petik satu
        System.out.println("Huruf \'A\'");

        // \\ = menampilkan tanda backslash
        System.out.println("Folder: C:\\Java\\Project");

        // \b = backspace
        System.out.println("ABC\bD");

        // \r = kembali ke awal baris
        System.out.println("Halo\rHi");

        // \f = form feed
        System.out.println("Halo\fDunia");
    }
    
}
